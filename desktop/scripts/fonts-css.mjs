// Writes src/app/fonts.css: the @font-face rules for the fonts the app ships.
//
// The app names "Inter" and "JetBrains Mono" all over its styles. Until 3.0.6
// it only named them: a computer without those fonts installed got whatever
// its "monospace" and "sans-serif" are, which on a Mac is a typewriter face
// for every note (issue 56). The files come from the @fontsource-variable
// packages; this script copies their rules under the plain family names the
// styles already use, so nothing else has to change.
//
// Run it after updating either package:  node scripts/fonts-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = [
  { pkg: 'inter', from: 'Inter Variable', family: 'Inter' },
  { pkg: 'jetbrains-mono', from: 'JetBrains Mono Variable', family: 'JetBrains Mono' },
];

let css = `/* Generated by scripts/fonts-css.mjs from the @fontsource-variable packages. Do not edit by hand. */\n`;
for (const { pkg, from, family } of FONTS) {
  const dir = path.join(root, 'node_modules', '@fontsource-variable', pkg);
  const { version } = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  css += `\n/* ${family}: @fontsource-variable/${pkg} ${version}, SIL Open Font License 1.1 (licenses/) */\n`;
  for (const file of ['wght.css', 'wght-italic.css']) {
    const rules = readFileSync(path.join(dir, file), 'utf8');
    if (!rules.includes(`font-family: '${from}'`)) throw new Error(`${pkg}/${file}: no rule for "${from}"`);
    css += rules
      .replaceAll(`font-family: '${from}'`, `font-family: '${family}'`)
      .replaceAll('url(./files/', `url(../../node_modules/@fontsource-variable/${pkg}/files/`)
      // The fonts are in the app, not on a server: nothing to wait for, so no swap flash.
      .replaceAll('font-display: swap', 'font-display: block')
      .trimEnd() + '\n';
  }
}
writeFileSync(path.join(root, 'src', 'app', 'fonts.css'), css);
console.log(`src/app/fonts.css: ${css.match(/@font-face/g).length} rules`);
